# v8_3/AI/__init__.py
"""网盘管理 V8_3 的 AI 层（从 V8 只读移植，代码与 V8 完全隔离）。

模块一览
========
* :mod:`v8_3.AI.队列特征分析` —— ``队列特征分析器``（纯计算）
* :mod:`v8_3.AI.时段预算`     —— ``时段管理器`` / ``预算管理器``
* :mod:`v8_3.AI.AI学习库`     —— ``AI学习库``（sqlite，默认 ``数据/AI学习库.db``）
* :mod:`v8_3.AI.DeepSeek价格抓取` —— ``DeepSeek价格抓取器``（httpx + 纯解析函数）
* :mod:`v8_3.AI.AI智能助手`   —— ``AI智能助手``（httpx 调 DeepSeek）
* :mod:`v8_3.AI.AI调度器`     —— ``AI调度器``（缓存/限频/学习闭环）
* :mod:`v8_3.AI.运行时`       —— ``AI运行时``（界面/引擎共用的门面）
* :mod:`v8_3.AI.配置适配`     —— 内部小工具（``取AI配置`` 等，不在本文件导出）

配置统一走 V8_3 自己的 ``v8_3.配置.AI配置()`` 普通 dict，不依赖 V8 的配置
加载器；无密钥 / AI 关闭时一律优雅降级为规则：不发网络请求、不抛异常。

最省事的用法（UI 里一行装配好所有部件）::

    import v8_3.AI as AI
    from v8_3.配置 import 加载配置

    配置 = 加载配置()
    组件 = AI.装配AI层(配置)          # 整份配置 dict 或 AI配置() 的 AI 段都行
    调度器 = 组件["AI调度器"]
    策略 = 调度器.请求策略(特征)

也可以单独构造（每个模块的 docstring 里都写了构造签名）::

    AI.AI智能助手(配置=配置)          # 助手自己补齐时段/预算
    AI.AI调度器(配置=配置)            # 调度器装配全部部件
"""
from .队列特征分析 import 队列特征分析器
from .时段预算 import 时段管理器, 预算管理器
from .AI学习库 import AI学习库
from .DeepSeek价格抓取 import DeepSeek价格抓取器
from .AI智能助手 import AI智能助手
from .AI调度器 import AI调度器
from .运行时 import AI运行时

__all__ = [
    "队列特征分析器",
    "时段管理器",
    "预算管理器",
    "AI学习库",
    "DeepSeek价格抓取器",
    "AI智能助手",
    "AI调度器",
    "AI运行时",
    "装配AI层",
]


def 装配AI层(配置=None, 学习库路径=None, 价格抓取器=None,
            自动刷新价格: bool = False, 初始化联网=None,
            禁用网络: bool = False, 建学习库=None) -> dict:
    """按 V8_3 的方式把 AI 层部件装配好，返回一个 dict。

    参数
    ----
    * ``配置``：整份配置 dict（含 ``"AI"``）或 ``AI配置()`` 的 AI 段；
      省略则用 ``AI配置()``（读 V8_3 自己的 ``配置.json``）；
    * ``学习库路径``：显式指定学习库 db；省略时只有 AI 真的启用
      （``启用`` 且 ``api密钥`` 非空）才建 ``AI学习库路径(配置)``，
      否则学习库为 ``None``（离线不落盘）；
    * ``价格抓取器``：不传就按配置新建一个；``自动刷新价格=False`` 表示
      构造阶段不联网，交给界面手动 ``手动刷新()``；
    * ``初始化联网`` / ``禁用网络``：透传给 ``AI智能助手``。

    返回的键：``配置``、``价格抓取器``、``时段管理器``、``预算管理器``、
    ``学习库``、``AI助手``、``AI调度器``、``相似度函数``。
    """
    from .配置适配 import 取AI配置          # 局部导入，保持顶层干净
    from ..配置 import AI学习库路径          # 默认落在 V8_3 的 数据/ 目录

    AI段 = 取AI配置(配置)
    可写配置 = 配置 if isinstance(配置, dict) else AI段

    if 价格抓取器 is None:
        价格抓取器 = DeepSeek价格抓取器(
            配置=AI段, 自动刷新=自动刷新价格,
            禁用网络=True if 禁用网络 else None)

    时段管理 = 时段管理器(价格抓取器=价格抓取器, 配置=AI段)
    预算管理 = 预算管理器(配置=可写配置)

    if 学习库路径 is not None:
        学习库 = AI学习库(学习库路径)
    else:
        要建库 = (bool(AI段.get("启用")) and bool(AI段.get("api密钥"))) \
            if 建学习库 is None else bool(建学习库)
        学习库 = AI学习库(AI学习库路径(可写配置)) if 要建库 else None

    助手 = AI智能助手(
        配置=可写配置, 时段管理器=时段管理, 预算管理器=预算管理,
        初始化联网=初始化联网, 禁用网络=禁用网络,
        价格抓取器=价格抓取器)

    调度器 = AI调度器(
        AI助手=助手, 时段管理器=时段管理, 预算管理器=预算管理,
        学习库=学习库, 相似度函数=队列特征分析器.相似度,
        配置=AI段, 禁用网络=禁用网络)

    return {
        "配置": AI段,
        "价格抓取器": 价格抓取器,
        "时段管理器": 时段管理,
        "预算管理器": 预算管理,
        "学习库": 学习库,
        "AI助手": 助手,
        "AI调度器": 调度器,
        "相似度函数": 队列特征分析器.相似度,
    }
