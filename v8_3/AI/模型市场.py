def 打分(条目: 模型条目, 权重: 推荐权重 | None = None) -> tuple[float, str]:
    """算出推荐指数（0~100）与一句推荐理由。

    分项都取自目录里明写的元数据，**不猜**：缺项按中性 0.5 参与。
    """
    权重 = (权重 or 默认权重).归一()
    任务 = float(条目.任务适配 or 0.5)
    中文 = float(条目.中文能力 or 0.5)
    推理 = float(条目.推理能力 or 0.5)
    轻 = float(条目.轻量 or 0.5)
    新 = float(条目.新鲜度 or 0.5)
    分 = (任务 * 权重.任务适配 + 中文 * 权重.中文能力
        + 推理 * 权重.推理能力 + 轻 * 权重.轻量 + 新 * 权重.新鲜度)
    # 官方库已下架/不存在：重罚，排到最后（但仍列出来，不骗人）
    if 条目.核对状态 == "不存在":
        分 *= 0.35
    分 = round(max(0.0, min(1.0, 分)) * 100, 1)

    理由 = []
    if 任务 >= 0.85:
        理由.append("与本项目的短中文决策任务高度匹配")
    if 中文 >= 0.85:
        理由.append("中文能力强")
    if 推理 >= 0.8:
        理由.append("推理扎实")
    if 轻 >= 0.85:
        理由.append("下载/内存都很轻")
    if 条目.参数B and 条目.参数B > 小模型上限B:
        理由.append("体积已超出小模型范畴")
    if 条目.核对状态 == "已核对" and 条目.体积字节:
        理由.append(f"官方库已核到 {条目.体积文本}")
    if not 理由:
        理由.append("综合表现均衡")
    return 分, "；".join(理由)


