def 构建目录(*, 联网: bool = True, 权重: 推荐权重 | None = None,
          进度回调: Optional[Callable[[str], None]] = None,
          上限: int = 60) -> list[模型条目]:
    """策展目录 + 动态拉取 + 注册表核对 → 打分排序后的完整目录。

    ``V8_3_不联网=1`` 时自动降级成纯策展目录（自检脚本据此保证离线）。
    """
    联网 = bool(联网) and not 联网被禁用()

    def 说(文本: str) -> None:
        if 进度回调 is not None:
            try:
                进度回调(文本)
            except Exception:
                pass

    条目表: dict[str, 模型条目] = {x.名字: x for x in 策展目录()}
    说(f"策展目录 {len(条目表)} 个模型")

    if 联网:
        说("正在从 Ollama 官方接口拉取热门模型…")
        try:
            动态 = 动态拉取热门小模型(上限=上限)
        except Exception:
            动态 = []
        新增 = 0
        for 项 in 动态:
            名字 = 项["名字"]
            if 名字 in 条目表:
                # 已有策展资料：只补动态大小
                if 项.get("大小") and not 条目表[名字].体积字节:
                    条目表[名字].体积字节 = int(项["大小"])
                continue
            系列 = 名字.split(":")[0]
            标签 = 名字.split(":", 1)[1] if ":" in 名字 else "latest"
            条目表[名字] = 模型条目(
                名字=名字, 标签=标签, 系列=系列,
                中文名=名字, 厂商="（动态发现）", 参数B=float(项.get("参数B") or 0),
                体积字节=int(项.get("大小") or 0), 许可证="需自查",
                总结="官方接口动态发现的小模型：资料还不全，可先安装试用。",
                简介=("这条是点『🔄 刷新目录』时从 Ollama 官方接口**动态发现**的：\n"
                    "• 参数 ≤ %.0fB，属于本项目能接受的小模型；\n"
                    "• 官方库还没有中文资料，装之前建议先看官方页面。" % 小模型上限B),
                适用场景=["试用"], 优点=["官方库可获取"], 注意=["资料不全"],
                中文能力=0.5, 推理能力=0.5, 轻量=0.6, 任务适配=0.5,
                新鲜度=0.8, 来源=str(项.get("来源") or "热门接口"),
                官方页=官方库地址.format(名字=系列),
                下载页=f"https://ollama.com/library/{名字}")
            新增 += 1
        说(f"动态发现 {新增} 个新模型")

        # 注册表核对：是否真能下载 + 精确体积。
        # ⚠️ 逐个串行要 70 秒（42 个模型 × 1.7s），用户点一次刷新得干等 ——
        #    改成 8 路并发，实测 10 秒内跑完。
        待核 = [x for x in 条目表.values() if x.核对状态 != "已核对"]
        说(f"正在核对 {len(待核)} 个模型的可下载状态与体积…")
        完成数 = {"n": 0}

        def 核一个(项: 模型条目) -> None:
            状态, 体积 = _解析体积(项.系列, 项.标签, 超时=12.0)
            项.核对状态 = 状态
            if 体积:
                项.体积字节 = 体积
                # 精确体积也能反推参数规模（Q4 大约 0.62 GB/B）——只在缺参数时用
                if not 项.参数B:
                    项.参数B = round(体积 / 1e9 / 0.62, 1)
            完成数["n"] += 1
            if 完成数["n"] % 5 == 0 or 完成数["n"] == len(待核):
                说(f"核对进度 {完成数['n']}/{len(待核)}")

        try:
            from concurrent.futures import ThreadPoolExecutor
            with ThreadPoolExecutor(max_workers=8) as 池:
                list(池.map(核一个, 待核))
        except Exception:
            for 项 in 待核:      # 并发不可用时退回串行
                核一个(项)

        # 注册表偶尔会掐掉并发连接（表现为"未核对"而不是"不存在"）：
        # 分批降并发重试到 3 轮，别把网络抖动当成"没有这个模型"。
        重试 = [x for x in 待核 if x.核对状态 == "未核对"]
        for 轮 in range(1, 4):
            if not 重试:
                break
            说(f"有 {len(重试)} 个没核到（网络抖动），低并发重试第 {轮} 轮…")
            线程数 = max(1, 4 - 轮)
            try:
                from concurrent.futures import ThreadPoolExecutor
                with ThreadPoolExecutor(max_workers=线程数) as 池:
                    list(池.map(核一个, 重试))
            except Exception:
                for 项 in 重试:
                    核一个(项)
            重试 = [x for x in 重试 if x.核对状态 == "未核对"]

    目录 = 排序并打分(list(条目表.values()), 权重)
    return 目录


def 读取缓存(*, 最长年龄: float = 缓存有效期) -> list[模型条目]:
    """读缓存；过期或损坏返回空列表。"""
    文件 = 缓存路径()
    try:
        数据 = json.loads(文件.read_text(encoding="utf-8"))
    except Exception:
        return []
    时间 = float(数据.get("时间") or 0)
    if 最长年龄 and 最长年龄 < 0:
        return []                      # 负数 = 强制视为过期（测试/强制重拉用）
    if 最长年龄 and (time.time() - 时间) > 最长年龄:
        return []
    条目们 = [模型条目.from_dict(x) for x in (数据.get("模型") or [])]
    # 缓存自检：打分依赖的分项字段一个都不能少（旧版本/半截写入的缓存直接作废，
    # 否则界面上会出现"推荐指数 0.0、总结空白"的坏卡片）。
    必填 = ("名字", "总结", "任务适配", "中文能力", "推理能力", "轻量", "新鲜度")
    if not 条目们 or any(
            not getattr(x, 名, None) for x in 条目们 for 名 in 必填):
        return []
    return 条目们


def 写入缓存(条目们: list[模型条目], 权重: 推荐权重 | None = None) -> None:
    文件 = 缓存路径()
    try:
        文件.parent.mkdir(parents=True, exist_ok=True)
        文件.write_text(json.dumps({
            "时间": time.time(),
            "权重": (权重 or 默认权重).to_dict(),
            "模型": [x.to_dict() for x in 条目们],
        }, ensure_ascii=False, indent=2), encoding="utf-8")
    except Exception:
        pass


def 清除缓存() -> None:
    try:
        缓存路径().unlink(missing_ok=True)
    except Exception:
        pass


def 缓存时间() -> float:
    try:
        数据 = json.loads(缓存路径().read_text(encoding="utf-8"))
        return float(数据.get("时间") or 0)
    except Exception:
        return 0.0


def 合并已装状态(条目们: list[模型条目],
               已装: dict[str, dict] | None = None) -> list[模型条目]:
    """把『本机已装/可升级』标到条目上（存进 注意 之外的两个动态字段）。

    * ``已安装``：本机 ollama 里有同名模型；
    * ``可更新``：本机有、且官方核到的体积比本机大 2% 以上（说明官方有新版）。
    """
    已装 = 已装 or {}
    小写表 = {k.lower(): v for k, v in 已装.items()}
    for 项 in 条目们:
        本机 = 小写表.get(项.名字.lower())
        项.本机体积 = int((本机 or {}).get("大小") or 0)
        项.已安装 = 本机 is not None
        官方 = int(项.体积字节 or 0)
        项.可更新 = bool(项.已安装 and 官方 and 项.本机体积
                     and 官方 > 项.本机体积 * 1.02)
    return 条目们


#: 上面两个动态字段挂在 dataclass 之外（它们不属于『目录数据』，是运行时状态）
模型条目.本机体积 = 0        # type: ignore[attr-defined]
模型条目.已安装 = False      # type: ignore[attr-defined]
模型条目.可更新 = False      # type: ignore[attr-defined]
