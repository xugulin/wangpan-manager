def _解析体积(名字: str, 标签: str, 超时: float = 15.0) -> tuple[str, int]:
    """核对一个模型标签是否可下载，并算出精确体积。

    :return: ``(核对状态, 体积字节)``；核对状态 ∈ 已核对 / 不存在 / 未核对
    """
    try:
        数据 = _http_json(注册表清单地址.format(名字=名字, 标签=标签), 超时)
    except Exception as e:  # noqa: BLE001
        码 = getattr(e, "code", None) or getattr(
            getattr(e, "response", None), "status_code", None)
        if 码 == 404:
            return "不存在", 0
        return "未核对", 0
    总量 = 0
    for 层 in (数据 or {}).get("layers") or []:
        try:
            总量 += int(层.get("size") or 0)
        except Exception:
            continue
    if 总量 <= 0:
        return "未核对", 0
    return "已核对", 总量


def _参数量(名字: str, 详情: dict | None = None) -> float:
    """从名字/详情里读参数量（B）。"""
    文本 = str((详情 or {}).get("parameter_size") or "")
    for 源 in (文本, 名字):
        匹配 = re.search(r"(\d+(?:\.\d+)?)\s*[bB]\b", 源)
        if 匹配:
            try:
                return float(匹配.group(1))
            except Exception:
                continue
    return 0.0


def 动态拉取热门小模型(上限: int = 25, 超时: float = 20.0) -> list[dict]:
    """从 Ollama 官方接口拉『热门模型』，只留**能确认是小模型**的。

    ⚠️ 两条硬规则（用户要的是"适用于本项目的小模型"，不能让 700 GB 的巨无霸混进来）：
      * 热门接口带 ``details.parameter_size``：解析得出参数量且 > 上限 → 丢弃；
      * 解析不出参数量的一律**不收** —— 无法证明它是小模型。
        （策展目录里手工收录的小模型不受影响。）
    """
    结果: list[dict] = []
    看到: set[str] = set()
    try:
        数据 = _http_json(热门接口, 超时)
        for 项 in (数据 or {}).get("models") or []:
            名字 = str(项.get("name") or 项.get("model") or "").strip()
            if not 名字 or 名字 in 看到:
                continue
            参数 = _参数量(名字, 项.get("details") or {})
            if not 参数 or 参数 > 小模型上限B:
                continue
            看到.add(名字)
            结果.append({"名字": 名字, "大小": int(项.get("size") or 0),
                       "修改时间": str(项.get("modified_at") or ""),
                       "来源": "热门接口", "参数B": 参数})
            if len(结果) >= 上限:
                break
    except Exception:
        pass
    return 结果


