def _http_json(地址: str, 超时: float = 20.0) -> Any:
    头 = {"user-agent": "Mozilla/5.0 (X11; Linux x86_64) V8_3-ModelMarket/1.0",
         "accept": "application/json"}
    if httpx is not None:
        with httpx.Client(timeout=超时, follow_redirects=True) as 客户端:
            响应 = 客户端.get(地址, headers=头)
            响应.raise_for_status()
            return 响应.json()
    req = urllib.request.Request(地址, headers=头)
    with urllib.request.urlopen(req, timeout=超时) as 应答:
        return json.loads(应答.read().decode("utf-8", "replace"))


