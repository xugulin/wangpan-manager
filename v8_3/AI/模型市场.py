@dataclass
class 推荐权重:
    """五个分项的权重（界面可调；和为 1 时分数最好解释，但不强制）。"""

    任务适配: float = 0.35      # 尺寸/能力与本项目『短中文决策任务』的匹配度
    中文能力: float = 0.20
    推理能力: float = 0.20
    轻量: float = 0.15          # 纯 CPU、内存占用、下载体积
    新鲜度: float = 0.10

    def 归一(self) -> "推荐权重":
        总 = (self.任务适配 + self.中文能力 + self.推理能力
             + self.轻量 + self.新鲜度)
        if 总 <= 0:
            return 推荐权重()
        return 推荐权重(self.任务适配 / 总, self.中文能力 / 总,
                      self.推理能力 / 总, self.轻量 / 总, self.新鲜度 / 总)

    def to_dict(self) -> dict:
        return {"任务适配": self.任务适配, "中文能力": self.中文能力,
                "推理能力": self.推理能力, "轻量": self.轻量,
                "新鲜度": self.新鲜度}

    @staticmethod
    def from_dict(数据: dict | None) -> "推荐权重":
        数据 = 数据 or {}
        return 推荐权重(
            float(数据.get("任务适配", 0.35)),
            float(数据.get("中文能力", 0.20)),
            float(数据.get("推理能力", 0.20)),
            float(数据.get("轻量", 0.15)),
            float(数据.get("新鲜度", 0.10))).归一()


默认权重 = 推荐权重()


@dataclass
class 模型条目:
    """一个可下载的本地小模型（目录项）。"""

    名字: str                       # ollama 模型名，如 deepseek-r1:1.5b
    标签: str = ""                  # 1.5b / 7b / latest
    系列: str = ""                  # deepseek-r1
    中文名: str = ""
    厂商: str = ""
    参数B: float = 0.0              # 参数量（十亿）
    量化: str = "Q4_K_M"
    体积字节: int = 0               # 动态核到的精确大小；0 = 未核到
    上下文: int = 0                 # tokens
    许可证: str = ""
    总结: str = ""                  # 一句话核心总结（界面加粗显示）
    简介: str = ""                  # 多行详细介绍
    适用场景: list[str] = field(default_factory=list)
    优点: list[str] = field(default_factory=list)
    注意: list[str] = field(default_factory=list)
    中文能力: float = 0.6           # 0~1
    推理能力: float = 0.5
    轻量: float = 0.5
    新鲜度: float = 0.5
    任务适配: float = 0.5
    可下载: bool = True             # 注册表核对结果
    核对状态: str = "未核对"        # 已核对 / 未核对 / 不存在
    官方页: str = ""
    下载页: str = ""
    来源: str = "策展"              # 策展 / 热门接口 / 库首页
    分数: float = 0.0
    推荐理由: str = ""

    # ---------------- 展示辅助 ----------------

    @property
    def 图片键(self) -> str:
        """本地图形标的键（见 图标.py）：按系列取色与字。"""
        return self.系列 or self.名字.split(":")[0]

    @property
    def 体积文本(self) -> str:
        if self.体积字节:
            return _人类体积(self.体积字节)
        # 没核到就按参数与量化粗估（Q4 大约 0.62 GB/B）
        if self.参数B:
            return f"约 {self.参数B * 0.62:.1f} GB"
        return "未知"

    def 详情行(self) -> list[tuple[str, str]]:
        """多行详细信息（界面按『标签：值』多行显示）。"""
        return [
            ("模型名", self.名字),
            ("系列 / 厂商", f"{self.系列 or '—'}　·　{self.厂商 or '—'}"),
            ("参数量 / 量化", f"{self.参数B or '?'}B　·　{self.量化 or '—'}"),
            ("下载体积", self.体积文本),
            ("上下文长度", f"{self.上下文} tokens" if self.上下文 else "—"),
            ("许可证", self.许可证 or "—"),
            ("中文能力", _星级(self.中文能力)),
            ("推理能力", _星级(self.推理能力)),
            ("轻量程度", _星级(self.轻量)),
            ("可用状态", self.可用文本()),
            ("适用场景", "、".join(self.适用场景) or "—"),
            ("下载地址", self.下载页),
            ("官方网站", self.官方页),
        ]

    def 可用文本(self) -> str:
        if self.核对状态 == "不存在":
            return "❌ 官方库已无此标签（可能改名或下架）"
        if self.核对状态 == "已核对":
            return "✅ 官方库可下载" + (f"（{self.体积文本}）" if self.体积字节 else "")
        return "❔ 未核对（点『🔄 刷新目录』联网核对）"

    def to_dict(self) -> dict:
        return {
            "名字": self.名字, "标签": self.标签, "系列": self.系列,
            "中文名": self.中文名, "厂商": self.厂商, "参数B": self.参数B,
            "量化": self.量化, "体积字节": self.体积字节, "上下文": self.上下文,
            "许可证": self.许可证, "总结": self.总结, "简介": self.简介,
            "适用场景": list(self.适用场景), "优点": list(self.优点),
            "注意": list(self.注意), "中文能力": self.中文能力,
            "推理能力": self.推理能力, "轻量": self.轻量,
            "新鲜度": self.新鲜度, "任务适配": self.任务适配,
            "可下载": self.可下载, "核对状态": self.核对状态,
            "官方页": self.官方页, "下载页": self.下载页, "来源": self.来源,
            "分数": self.分数, "推荐理由": self.推荐理由,
        }

    @staticmethod
    def from_dict(数据: dict) -> "模型条目":
        字段名 = {f for f in 模型条目.__dataclass_fields__}
        干净 = {k: v for k, v in (数据 or {}).items() if k in 字段名}
        return 模型条目(**干净)


def _人类体积(字节: int) -> str:
    try:
        数 = float(字节)
    except Exception:
        return "未知"
    for 单位 in ("B", "KB", "MB", "GB", "TB"):
        if 数 < 1000 or 单位 == "TB":
            return f"{数:.2f} {单位}" if 单位 not in ("B", "KB") else f"{数:.0f} {单位}"
        数 /= 1000.0
    return f"{数:.2f} TB"


def _星级(值: float) -> str:
    值 = max(0.0, min(1.0, float(值 or 0)))
    满 = int(round(值 * 5))
    return "★" * 满 + "☆" * (5 - 满) + f"（{值 * 100:.0f}%）"


