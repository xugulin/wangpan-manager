def 构建工具栏(动作表: dict, 父=None, 隐藏项=()) -> QToolBar:
    """VLC 风格工具栏：打开 | 播放控制 | 全屏 清单 AI 循环 随机 | 音量 | 速度 | 面板。

    :param 隐藏项: 不放上工具栏的键（例如独立播放器要求去掉
        「打开网盘 / 打开文件 / 播放清单 / AI 助手」—— 它们仍在菜单里可用）。

    **三档宽度自适应**（用户要求"速度和面板都要显示文字"）：
    ``完整`` → ``📂 打开网盘 … 🔊 100% ──── 速度 [1.0×] 🗂 面板``（约 1270px）
    ``精简`` → ``📂 网盘 … 🔊 ──── 速度 [1.0×] 🗂 面板``（约 1050px，**保留文字**）
    ``图标`` → 只有图标，说明进 tooltip（很窄时用）
    宿主在 resizeEvent 里调 ``按宽度自适应(窗口宽)``；判据是 `sizeHint()`（真实需要
    宽度），并且**每次换档后都复核**，避免"展开后反而装不下被无声裁掉"。
    """
    栏 = QToolBar("播放", 父)
    栏.setMovable(False)
    栏.setToolButtonStyle(Qt.ToolButtonTextOnly)
    栏.setIconSize(QSize(16, 16))
    # 收紧内边距：一档文字能省下 100+px，这是"1183px 也能显示文字"的关键
    栏.setStyleSheet("QToolBar{padding:1px;spacing:2px;}"
                   "QToolButton{padding:1px 5px;margin:0px;}")

    # (键, 图标, 精简文字, 完整文字, 提示, 额外)
    规格 = [
        ("打开网盘", "📂", "📂 网盘", "📂 打开网盘",
         "在网盘里挑视频（与传输页同一个选择器）", {}),
        ("打开本地", "📁", "📁 文件", "📁 打开文件", "播放本机文件", {}),
        ("__sep__", "", "", "", "", {}),
        ("播放暂停", "▶", "▶ 播放", "▶ 播放", "播放 / 暂停（空格）",
         {"属性": "播放动作", "快捷键": "Space"}),
        ("停止", "⏹", "⏹ 停止", "⏹ 停止", "停止（S）", {"属性": "停止动作"}),
        ("上一个", "⏮", "⏮ 上一", "⏮ 上一个", "播放清单里的上一个（N）",
         {"属性": "上一个动作"}),
        ("下一个", "⏭", "⏭ 下一", "⏭ 下一个", "播放清单里的下一个（B）",
         {"属性": "下一个动作"}),
        ("__sep__", "", "", "", "", {}),
        ("全屏", "⛶", "⛶ 全屏", "⛶ 全屏",
         "全屏（F）；全屏时控件自动隐藏，Esc 退出全屏",
         {"属性": "全屏动作", "勾选": True}),
        ("切换清单", "📋", "📋 清单", "📋 播放清单", "显示/隐藏播放清单（Ctrl+L）",
         {"属性": "清单动作", "勾选": True}),
        ("切换AI面板", "🤖", "🤖 AI", "🤖 AI 助手", "显示 AI 助手面板",
         {"属性": "AI面板动作", "勾选": True}),
        ("循环切换", "🔁", "🔁 不循环", "🔁 不循环",
         "循环模式：不循环 / 单曲 / 列表", {"属性": "循环动作"}),
        ("随机切换", "🔀", "🔀 随机", "🔀 随机", "随机播放",
         {"属性": "随机动作", "勾选": True}),
        ("__sep__", "", "", "", "", {}),
        ("静音切换", "🔊", "🔊", "🔊", "静音 / 取消静音（M）",
         {"属性": "静音按钮", "勾选": True}),
    ]
    栏.动作文本表 = {}
    栏.动作索引 = {}
    栏.动作们 = []
    _藏 = {str(x) for x in (隐藏项 or ())}
    for 键, 图标, 精简, 完整, 提示, 额外 in 规格:
        if 键 == "__sep__":
            栏.addSeparator()
            continue
        if 键 in _藏:
            continue
        动作 = _加项(栏, 动作表, 键, 完整, 提示=提示,
                   勾选=bool(额外.get("勾选")), 传选中=bool(额外.get("勾选")),
                   快捷键=额外.get("快捷键"))
        栏.动作文本表[键] = (图标, 精简, 完整)
        栏.动作索引[键] = 动作
        栏.动作们.append(动作)
        if 额外.get("属性"):
            setattr(栏, 额外["属性"], 动作)

    栏.音量滑条 = QSlider(Qt.Horizontal)
    栏.音量滑条.setRange(0, 150)
    栏.音量滑条.setValue(100)
    栏.音量滑条.setFixedWidth(90)
    栏.音量滑条.setToolTip("音量（↑/↓ 也能调）")
    if _取(动作表, "设置音量"):
        栏.音量滑条.valueChanged.connect(
            lambda v: 动作表["设置音量"](int(v)))
    else:
        栏.音量滑条.setEnabled(False)
    栏.音量标签 = QLabel(" 100% ")
    栏.音量标签.setToolTip("当前音量")
    栏.addWidget(栏.音量滑条)
    栏.addWidget(栏.音量标签)
    栏.addSeparator()

    # 「速度」标签必须显示（用户明确要求）
    栏.速度标签 = QLabel(" 速度 ")
    栏.速度标签.setToolTip("播放速度")
    栏.addWidget(栏.速度标签)
    栏.速度框 = QComboBox()
    for 倍速 in 速度表:
        栏.速度框.addItem(f"{倍速}×", float(倍速))
    栏.速度框.setCurrentIndex(速度表.index(1.0))
    栏.速度框.setFixedWidth(74)
    栏.速度框.setToolTip("播放速度（VLC 同款档位：0.25×~4×）")
    if _取(动作表, "设置速度"):
        栏.速度框.currentIndexChanged.connect(
            lambda _i: 动作表["设置速度"](float(栏.速度框.currentData() or 1.0)))
    else:
        栏.速度框.setEnabled(False)
    栏.addWidget(栏.速度框)
    栏.addSeparator()

    # 需求：在「速度」后面放一个"显示/隐藏 播放清单/AI 助手面板"的按钮（文字显示）
    if "切换侧栏" not in _藏:
        栏.侧栏动作 = _加项(栏, 动作表, "切换侧栏", "🗂 面板", 勾选=True,
                      传选中=True,
                      提示="显示 / 隐藏右侧的「播放清单 + AI 助手」面板")
        栏.动作文本表["切换侧栏"] = ("🗂", "🗂 面板", "🗂 面板")
        栏.动作索引["切换侧栏"] = 栏.侧栏动作
        栏.动作们.append(栏.侧栏动作)
    else:
        栏.侧栏动作 = None

    栏.模式们 = ("完整", "精简", "图标")

    #: 各档的按钮左右内边距（px）。**Windows 上中文字体 + emoji 天生更宽**，
    #: 同一档在 Windows 上比 Linux 宽 20~30%（真机 CI 实测：图标档都要 979px），
    #: 所以窄档再收紧内边距，把这部分差距吃回来。
    档内边距 = {"完整": 5, "精简": 3, "图标": 2}
    栏._内边距 = None

    #: 窄到连图标档都装不下时，按这个顺序把工具栏入口收起来
    #: （它们全都还在右键菜单 / 菜单栏里，收掉的只是工具栏上那个入口）
    可收起顺序 = ("循环切换", "随机切换", "上一个", "下一个")

    def 设置模式(模式: str = "完整", 可用宽度: int = 0):
        """切换三档文字密度；顺带按宽度收紧音量/速度控件。"""
        if 模式 not in 栏.模式们:
            模式 = "完整"
        # 每一档都先**恢复**被收起的入口（窗口变宽时要把它们放回来）
        for 动作 in 栏.动作们:
            动作.setVisible(True)
        栏.音量滑条.setVisible(True)
        内边距 = 档内边距.get(模式, 5)
        if 栏._内边距 != 内边距:
            栏._内边距 = 内边距
            栏.setStyleSheet("QToolBar{padding:1px;spacing:2px;}"
                          f"QToolButton{{padding:1px {内边距}px;margin:0px;}}")
        for 动作 in 栏.动作们:
            图标 = 精简 = 完整 = None
            for _键, (图, 简, 全) in 栏.动作文本表.items():
                if 动作.text() in (图, 简, 全):
                    图标, 精简, 完整 = 图, 简, 全
                    break
            if 图标 is None:
                continue
            动作.setText({"图标": 图标, "精简": 精简, "完整": 完整}[模式])
        宽 = int(可用宽度 or 栏.width() or 1200)
        栏.音量标签.setVisible(模式 != "图标" and 宽 >= 1150)
        if 模式 == "图标":
            栏.音量滑条.setFixedWidth(44)
        elif 模式 == "精简":
            栏.音量滑条.setFixedWidth(64)
        else:
            栏.音量滑条.setFixedWidth(80 if 宽 < 1250 else 100)
        栏.速度框.setFixedWidth(54 if 模式 == "图标" else (64 if 模式 == "精简" else 74))
        栏.速度标签.setVisible(模式 != "图标")
        栏.当前模式 = 模式

    def 按宽度自适应(宽度: int = 0):
        """从最宽松的档位往下试，**每档都复核真实需要宽度**，选第一个装得下的。

        踩过的坑：①硬阈值判断不出"1188px 装不下 ~1400px"；②按需要宽度判断后，
        "展开"那一步没有复核，展开后反而超出被裁掉。现在逐档复核。
        """
        宽 = int(宽度 or 栏.width() or 1200)
        if getattr(栏, "当前模式", None) is None:
            栏.当前模式 = None
        def 装得下() -> bool:
            try:
                栏.updateGeometry()
            except Exception:  # noqa: BLE001
                pass
            return int(栏.sizeHint().width() or 0) <= 宽 - 4

        for 模式 in 栏.模式们:
            设置模式(模式, 宽)
            if 装得下():
                return 模式
        # 连图标档都装不下（窄窗口 / Windows 字体更宽）：继续收 ——
        # 先收音量滑条（音量还有静音键和 ↑↓ 快捷键），再按顺序收「菜单里也有」的按钮
        设置模式("图标", 宽)
        栏.音量滑条.setVisible(False)
        栏.音量标签.setVisible(False)
        if not 装得下():
            for 键 in 可收起顺序:
                动作 = 栏.动作索引.get(键)
                if 动作 is not None:
                    动作.setVisible(False)
                if 装得下():
                    break
        return "图标"

    栏.设置模式 = 设置模式
    栏.按宽度自适应 = 按宽度自适应
    栏.当前模式 = None
    按宽度自适应(0)
    return 栏


