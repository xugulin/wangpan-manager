def _取(动作表: dict, 键: str) -> Optional[Callable]:
    函数 = (动作表 or {}).get(键)
    return 函数 if callable(函数) else None


def _加项(菜单, 动作表: dict, 键: str, 文本: str, *,
         快捷键=None, 勾选: bool = False, 传选中: bool = False,
         提示: str = "", 分组=None) -> QAction:
    """加一个菜单项；动作表里没有这个键就置灰（而不是让整个菜单崩掉）。"""
    动作 = QAction(文本, 菜单)
    if 快捷键:
        动作.setShortcut(快捷键)
    函数 = _取(动作表, 键)
    if 函数 is None:
        动作.setEnabled(False)
        动作.setToolTip(提示 or "当前界面不支持这个操作")
    else:
        if 勾选:
            动作.setCheckable(True)
            try:
                动作.setChecked(bool(动作表.get("是否" + 键, lambda: False)()))
            except Exception:  # noqa: BLE001
                pass
        if 传选中:
            动作.triggered.connect(lambda 选中=False, f=函数: f(bool(选中)))
        else:
            动作.triggered.connect(lambda _=False, f=函数: f())
    if 提示:
        动作.setToolTip(提示)
    if 分组 is not None:
        分组.addAction(动作)
    菜单.addAction(动作)
    return 动作


def _加分隔(菜单):
    菜单.addSeparator()


def _轨道子菜单(菜单: QMenu, 动作表: dict, 列表键: str, 选择键: str,
            当前键: str = "", 空提示: str = "（没有可切换的轨道）"):
    """动态填充"音频轨/字幕轨"子菜单（每次弹出时重拉，VLC 同款）。"""

    def _填充():
        菜单.clear()
        列表函数 = _取(动作表, 列表键)
        选择函数 = _取(动作表, 选择键)
        当前 = -999
        if 当前键 and _取(动作表, 当前键):
            try:
                当前 = int(动作表[当前键]())
            except Exception:  # noqa: BLE001
                当前 = -999
        轨道们 = []
        if 列表函数 is not None:
            try:
                轨道们 = list(列表函数() or [])
            except Exception:  # noqa: BLE001
                轨道们 = []
        if not 轨道们:
            空 = QAction(空提示, 菜单)
            空.setEnabled(False)
            菜单.addAction(空)
            return
        组 = QActionGroup(菜单)
        组.setExclusive(True)
        for 编号, 名称 in 轨道们:
            文本 = f"{'✔ ' if int(编号) == 当前 else '   '}{名称 or f'轨道 {编号}'}"
            动作 = QAction(文本, 菜单)
            动作.setCheckable(True)
            动作.setChecked(int(编号) == 当前)
            组.addAction(动作)
            if 选择函数 is None:
                动作.setEnabled(False)
            else:
                动作.triggered.connect(
                    lambda _=False, n=int(编号), f=选择函数: f(n))
            菜单.addAction(动作)

    菜单.aboutToShow.connect(_填充)
    _填充()


def _章节子菜单(菜单: QMenu, 动作表: dict, 空提示: str = "（这个文件没有章节）"):
    def _填充():
        菜单.clear()
        数函数 = _取(动作表, "章节数")
        数 = 0
        if 数函数 is not None:
            try:
                数 = int(数函数() or 0)
            except Exception:  # noqa: BLE001
                数 = 0
        当前 = -1
        if _取(动作表, "当前章节"):
            try:
                当前 = int(动作表["当前章节"]())
            except Exception:  # noqa: BLE001
                当前 = -1
        if 数 <= 0:
            空 = QAction(空提示, 菜单)
            空.setEnabled(False)
            菜单.addAction(空)
            return
        选择 = _取(动作表, "跳章节")
        组 = QActionGroup(菜单)
        for i in range(数):
            动作 = QAction(f"{'✔ ' if i == 当前 else '   '}第 {i + 1} 章", 菜单)
            动作.setCheckable(True)
            动作.setChecked(i == 当前)
            组.addAction(动作)
            if 选择 is None:
                动作.setEnabled(False)
            else:
                动作.triggered.connect(lambda _=False, n=i, f=选择: f(n))
            菜单.addAction(动作)

    菜单.aboutToShow.connect(_填充)
    _填充()


